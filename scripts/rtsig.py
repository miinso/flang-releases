#!/usr/bin/env python3
# scan the flang runtime api headers for parameters whose width follows the target (size_t, ptrdiff_t and aliases),
# which the host-compiled type models in RTBuilder.h cannot tell apart from fixed 64-bit integers.
# usage: rtsig.py <flang/include/flang/Runtime> [--inc out.inc]
import re, sys, glob, os, collections

SIZE = re.compile(r"\b(std::)?size_t\b")
PDIFF = re.compile(r"\b(SubscriptValue|(std::)?ptrdiff_t|(std::)?u?intptr_t|CFI_index_t)\b")
FIX64 = re.compile(r"\b(u?int64_t|InquiryKeywordHash|TypeParameterValue|long long)\b")
HOSTLONG = re.compile(r"\b(unsigned\s+long|long)\b(?!\s+(long|double))")
PFX = {"RTDECL": "_FortranA", "RTNAME": "_FortranA", "RTDEF": "_FortranA", "IODECL": "_FortranAio", "IONAME": "_FortranAio", "IODEF": "_FortranAio"}

def split_args(a):
    out, depth, cur = [], 0, ""
    for ch in a:
        if ch in "(<[":
            depth += 1
        elif ch in ")>]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [re.sub(r"\s+", " ", x.split("=")[0]).strip() for x in out]

def cls(t):
    ind = "*" if ("*" in t or "&" in t) else ""
    if "(" in t:
        return "fn" if (SIZE.search(t) or PDIFF.search(t)) else ""
    if SIZE.search(t): return "S" + ind
    if PDIFF.search(t): return "P" + ind
    if FIX64.search(t): return "64" + ind
    if HOSTLONG.search(t): return "L" + ind
    return ""

funcs = {}
for f in sorted(glob.glob(os.path.join(sys.argv[1], "*.h")) + glob.glob(os.path.join(sys.argv[1], "*.inc"))):
    s = open(f).read()
    s = re.sub(r"//[^\n]*", "", s); s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    for m in re.finditer(r"\b(RTDECL|RTNAME|IODECL|IONAME)\((\w+)\)\s*\(", s):
        i = m.end(); depth = 1
        while depth and i < len(s):
            depth += s[i] == "("; depth -= s[i] == ")"; i += 1
        args = split_args(s[m.end():i - 1])
        j = max(s.rfind(c, 0, m.start()) for c in ";{}") + 1
        ret = re.sub(r"\s+", " ", s[j:m.start()]).strip()
        ret = re.sub(r"^(extern \"C\"|RT_API_ATTRS|NORETURN|\[\[noreturn\]\]|#\w+[^\n]*)\s*", "", ret)
        name = PFX[m.group(1)] + m.group(2)
        funcs.setdefault(name, (os.path.basename(f), ret, args))

kinds = collections.Counter()
rows = []
for name, (f, ret, args) in sorted(funcs.items()):
    c = [cls(ret)] + [cls(a) for a in args]
    for k in c:
        if k: kinds[k] += 1
    if any(k and not k.startswith("64") for k in c):
        rows.append((name, f, c, ret, args))
print(len(funcs), "entry points,", len(rows), "with target-width or host-long params;", dict(kinds))
for name, f, c, ret, args in rows:
    print(f"{name:44s} {f:22s} ret={c[0] or '-':3s} " + " ".join(f"{i}:{k}" for i, k in enumerate(c[1:]) if k))
if "--inc" in sys.argv:
    out = sys.argv[sys.argv.index("--inc") + 1]
    with open(out, "w") as o:
        o.write("// generated by rtsig.py from flang/include/flang/Runtime: runtime entry points with\n"
                "// parameters whose width follows the target (size_t, ptrdiff_t). name, result, argument mask.\n")
        for name, f, c, ret, args in rows:
            mask = sum(1 << i for i, k in enumerate(c[1:]) if k in ("S", "P"))
            r = 1 if c[0] in ("S", "P") else 0
            if mask or r:
                o.write(f'TARGET_WIDTH_RT("{name}", {r}, 0x{mask:x})\n')
